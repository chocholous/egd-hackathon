import fs from 'node:fs';
import { genDocx } from './src/gen-docx.mjs';
import { makeTemplate, genDocxFromTemplate } from './src/gen-docxtpl.mjs';
import { genExcelJs } from './src/gen-exceljs.mjs';
import { genSheetJs } from './src/gen-sheetjs.mjs';
import { genPptx } from './src/gen-pptx.mjs';
import { genPdfLib, genPdfLibStdFont } from './src/gen-pdf.mjs';
import { genPdfMake } from './src/gen-pdfmake.mjs';
import { genJsPdfDefault, genJsPdfFont } from './src/gen-jspdf.mjs';
const out = process.argv[2] ?? 'out'; fs.mkdirSync(out, { recursive: true });
const reg = new Uint8Array(fs.readFileSync('src/Roboto-Regular.ttf')), bold = new Uint8Array(fs.readFileSync('src/Roboto-Medium.ttf'));
const w = (n, b) => { fs.writeFileSync(`${out}/${n}`, b); console.log('OK', n, b.length); };
const tryit = async (n, f) => { try { w(n, await f()); } catch (e) { console.log('FAIL', n, e.message); } };
await tryit('docx-lib.docx', genDocx);
const tpl = await makeTemplate(); w('sablona.docx', tpl);
await tryit('docx-sablona.docx', () => genDocxFromTemplate(tpl));
await tryit('xlsx-exceljs.xlsx', genExcelJs);
await tryit('xlsx-sheetjs.xlsx', genSheetJs);
await tryit('pptx-pptxgenjs.pptx', genPptx);
await tryit('pdf-pdflib.pdf', () => genPdfLib(reg));
await tryit('pdf-pdflib-stdfont.pdf', genPdfLibStdFont);
await tryit('pdf-pdfmake.pdf', () => genPdfMake(reg, bold));
await tryit('pdf-jspdf-default.pdf', async () => genJsPdfDefault());
await tryit('pdf-jspdf-roboto.pdf', async () => genJsPdfFont(Buffer.from(reg).toString('base64')));
